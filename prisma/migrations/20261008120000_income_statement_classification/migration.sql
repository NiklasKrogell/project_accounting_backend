-- Aligns AccountMainClass with the numbered items of the statutory income
-- statement layout (PMA 1753/2015, Annex I) and adds the lettered sub-items as
-- a nullable classification on AccountGroup.
--
-- Hand-written: Prisma would recreate the enum, losing its order. The enum's
-- sort order IS the statutory order (the chart of accounts and the income
-- statement both order by it), hence the explicit BEFORE/AFTER positions.
--
-- No rows are rewritten. Groups that were APPROPRIATIONS_AND_TAXES become
-- APPROPRIATIONS; any tax accounts in them must be moved to INCOME_TAXES /
-- OTHER_DIRECT_TAXES groups by hand.

-- AlterEnum
ALTER TYPE "AccountMainClass" RENAME VALUE 'APPROPRIATIONS_AND_TAXES' TO 'APPROPRIATIONS';
ALTER TYPE "AccountMainClass" ADD VALUE 'CHANGE_IN_FINISHED_GOODS_INVENTORIES' AFTER 'REVENUE';
ALTER TYPE "AccountMainClass" ADD VALUE 'PRODUCTION_FOR_OWN_USE' AFTER 'CHANGE_IN_FINISHED_GOODS_INVENTORIES';
ALTER TYPE "AccountMainClass" ADD VALUE 'OTHER_OPERATING_INCOME' AFTER 'PRODUCTION_FOR_OWN_USE';
ALTER TYPE "AccountMainClass" ADD VALUE 'INCOME_TAXES' AFTER 'APPROPRIATIONS';
ALTER TYPE "AccountMainClass" ADD VALUE 'OTHER_DIRECT_TAXES' AFTER 'INCOME_TAXES';

-- CreateEnum
CREATE TYPE "IncomeStatementSubItem" AS ENUM (
  'PURCHASES',
  'CHANGE_IN_INVENTORIES',
  'EXTERNAL_SERVICES',
  'WAGES_AND_SALARIES',
  'PENSION_EXPENSES',
  'OTHER_SOCIAL_SECURITY_EXPENSES',
  'PLANNED_DEPRECIATION',
  'IMPAIRMENT_OF_FIXED_ASSETS',
  'EXCEPTIONAL_IMPAIRMENT_OF_CURRENT_ASSETS',
  'INCOME_FROM_GROUP_UNDERTAKINGS',
  'INCOME_FROM_PARTICIPATING_INTERESTS',
  'INCOME_FROM_OTHER_FIXED_ASSET_INVESTMENTS',
  'INCOME_FROM_OTHER_FIXED_ASSET_INVESTMENTS_GROUP_UNDERTAKINGS',
  'OTHER_INTEREST_AND_FINANCIAL_INCOME',
  'OTHER_INTEREST_AND_FINANCIAL_INCOME_GROUP_UNDERTAKINGS',
  'IMPAIRMENT_OF_FIXED_ASSET_INVESTMENTS',
  'IMPAIRMENT_OF_CURRENT_ASSET_SECURITIES',
  'INTEREST_AND_OTHER_FINANCIAL_EXPENSES',
  'INTEREST_AND_OTHER_FINANCIAL_EXPENSES_GROUP_UNDERTAKINGS',
  'CHANGE_IN_DEPRECIATION_DIFFERENCE',
  'CHANGE_IN_TAX_BASED_PROVISIONS',
  'GROUP_CONTRIBUTION'
);

-- AlterTable
ALTER TABLE "AccountGroup" ADD COLUMN "incomeStatementSubItem" "IncomeStatementSubItem";

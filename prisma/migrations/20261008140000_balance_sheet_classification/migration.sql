-- Adds what the statutory balance sheet layout (PMA 1753/2015, Annex V) needs
-- on top of the main classes: section B of Vastattavaa (Tilinpäätössiirtojen
-- kertymä) as a main class, and the layout's items as a nullable
-- classification on AccountGroup.
--
-- Hand-written for the same reason as the income statement migration: the
-- enum's sort order IS the statutory order, hence the explicit AFTER position.
--
-- No rows are rewritten; existing balance sheet groups simply have no item yet.

-- AlterEnum
ALTER TYPE "AccountMainClass" ADD VALUE 'ACCUMULATED_APPROPRIATIONS' AFTER 'EQUITY';

